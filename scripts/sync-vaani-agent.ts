/**
 * Build the Aangan agent prompt from the live knowledge files and push it to Vaani.
 *   npm run vaani:sync -- --dry-run    write docs/vaani-agent-prompt.md only, no API call
 *   npm run vaani:sync                 create the agent (or update it if VAANI_AGENT_ID is set)
 * Re-run after any change to knowledge/*.md.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadEnvFile } from "node:process";
import { loadConfig } from "../src/lib/config";
import { loadKnowledge } from "../src/lib/knowledge";
import { buildPersona } from "../src/lib/vaani/agent-prompt";
import { VaaniRestClient } from "../src/lib/vaani/client";

const root = join(import.meta.dirname, "..");
const envPath = join(root, ".env.local");
try { loadEnvFile(envPath); } catch { /* env may already be set */ }

async function main() {
  const dry = process.argv.includes("--dry-run");
  const config = loadConfig({ ...process.env, KNOWLEDGE_DIR: join(root, "knowledge") });
  const knowledge = await loadKnowledge(config.knowledgeDir);
  const persona = buildPersona(knowledge, config);
  const prompt = (persona.identity as { system_prompt: string }).system_prompt;
  const sha = createHash("sha256").update(JSON.stringify(knowledge)).digest("hex").slice(0, 12);

  writeFileSync(
    join(root, "docs", "vaani-agent-prompt.md"),
    `<!-- Generated by npm run vaani:sync. Knowledge files sha256 (first 12): ${sha}. Do not edit by hand. -->\n\n${prompt}`,
  );
  console.log(`Prompt built: ${prompt.length} characters, knowledge sha ${sha}. Written to docs/vaani-agent-prompt.md`);
  if (dry) return;

  const apiKey = process.env.VAANI_API_KEY;
  if (!apiKey) throw new Error("VAANI_API_KEY is not set");
  const client = new VaaniRestClient({ apiKey, baseUrl: process.env.VAANI_API_URL });
  const existing = process.env.VAANI_AGENT_ID;
  if (existing) {
    await client.updatePersona(existing, persona);
    console.log(`Updated persona of agent ${existing}`);
    return;
  }
  const { agentId } = await client.createAgent("Aangan Studio enquiry agent", { persona });
  const env = readFileSync(envPath, "utf8");
  writeFileSync(envPath, `${env.replace(/\n*$/, "\n")}VAANI_AGENT_ID=${agentId}\n`);
  console.log(`Created agent ${agentId}. Saved VAANI_AGENT_ID to .env.local`);
}
main().catch((e) => {
  console.error(String(e.message ?? e).replace(/vaani_[a-z0-9]+/gi, "[redacted]"));
  process.exit(1);
});
